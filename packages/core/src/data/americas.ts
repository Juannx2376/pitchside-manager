// Registro oficial de divisiones de América (temporada 2026; Chile y Perú-Liga2 con la última lista disponible).
// Fuente: Wikipedia (listas de equipos de cada campeonato). Sirve para corregir la base de datos importada:
// qué club juega en qué categoría, el tamaño oficial de cada liga y los clubes que faltan en los datos FC26.
//
// Formato de cada club:  'Nombre canónico @ Ciudad #idExterno | alias | alias'
//   · `#idExterno` fuerza el emparejamiento con un club del dataset (útil con nombres ambiguos).
//   · los alias sirven para emparejar con los nombres que traen FC26 / Wikidata.

export interface RegistryClub {
  name: string;
  city?: string;
  ext?: string;
  aliases: string[];
}

export interface DivisionDef {
  country: string;
  tier: number;
  /** Nombre oficial de la competición. */
  name: string;
  /** Tamaño oficial: si hay menos clubes en la lista, el resto se genera. */
  size: number;
  clubs: RegistryClub[];
}

function parse(entry: string): RegistryClub {
  const [head, ...aliases] = entry.split('|').map((s) => s.trim());
  let name = head;
  let city: string | undefined;
  let ext: string | undefined;
  const hash = name.indexOf('#');
  if (hash >= 0) {
    ext = name.slice(hash + 1).trim();
    name = name.slice(0, hash).trim();
  }
  const at = name.indexOf('@');
  if (at >= 0) {
    city = name.slice(at + 1).trim();
    name = name.slice(0, at).trim();
  }
  return { name, city, ext, aliases };
}

function div(country: string, tier: number, name: string, size: number, clubs: string[]): DivisionDef {
  return { country, tier, name, size, clubs: clubs.map(parse) };
}

